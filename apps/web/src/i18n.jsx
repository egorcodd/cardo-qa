const DICT = { ru: RU, en: EN };

function format(str, vars) {
  return vars
    ? str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : ""))
    : str;
}

const LangCtx = createContext({ lang: "ru", setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, updateLang] = useState(() =>
    localStorage.getItem("cardo_language") === "en" ? "en" : "ru",
  );
  const setLang = (value) => {
    updateLang(value);
    localStorage.setItem("cardo_language", value);
    document.documentElement.lang = value;
  };
  const t = (k, vars) =>
    format(
      (DICT[lang] && DICT[lang][k]) != null
        ? DICT[lang][k]
        : RU[k] != null
          ? RU[k]
          : k,
      vars,
    );
  return (
    <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>
  );
}

export const useLang = () => useContext(LangCtx);
